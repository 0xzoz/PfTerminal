"""Write the Tart parity record's results.json, dispositions.md and parity.md from tools/tart-dispositions.json
(the integrator's judgments), design/baseline.json (the UTM baseline per case) and the assembled runs/.
usage: make_results_par.py RECORD_DIR"""
import collections
import hashlib
import json
import pathlib
import sys

rec = pathlib.Path(sys.argv[1])
tools = rec / "tools"
judg = json.loads((tools / "tart-dispositions.json").read_text())
base = {b["id"]: b for b in json.loads((rec / "design/baseline.json").read_text())}
design = json.loads((rec / "design.json").read_text())
prio = {c["id"]: c.get("priority", "blocker") for c in design["cases"]}
prio.update({"MOD-34": "blocker"})


def sha(p):
    return hashlib.sha256(p.read_bytes()).hexdigest()


def result_md(label):
    for p in ("collected/evidence/result.md", "collected/work/evidence/result.md"):
        f = rec / "runs" / label / p
        if f.exists():
            return f
    return None


cases = []
for cid in sorted(judg):
    j, b = judg[cid], base[cid]
    attempts = []
    for label, kind in [(j["group"], "first attempt (counts)")] + \
            [(j[k]["group"], k) for k in ("replay", "tiebreak", "postcap_replay") if k in j]:
        rm = result_md(label)
        iso = rec / "runs" / label / f"isolation-{cid}.json"
        attempts.append({"group": label, "kind": kind,
                         "executor_verdict": j["executor"] if label == j["group"] else
                         next(j[k]["executor"] for k in ("replay", "tiebreak", "postcap_replay") if k in j and j[k]["group"] == label),
                         "result": {"path": str(rm.relative_to(rec)), "sha256": sha(rm)} if rm else None,
                         "isolation_record": {"path": str(iso.relative_to(rec)), "sha256": sha(iso)} if iso.exists() else None})
    cases.append({
        "id": cid, "priority": prio.get(cid, "blocker"), "disposition": j["disposition"],
        "owner_decision": j.get("owner"), "summary": j["summary"],
        "candidate_sha256": "15cb32e9407cc346286d39f24514bb391027db10d2aceb12c1c2798e482c4ae6",
        "machine": "Tart clone of corbanu-qa-base (macOS 26.6.2), one fresh clone per group",
        "method": "tmux", "code_blind": True, "fresh_context": True, "results_blind": True,
        "attempts": attempts,
        "parity": {"class": j["parity"], "attribution": j.get("attribution"), "note": j.get("attribution_note"),
                   "utm_baseline": {k: b[k] for k in ("utm_record", "utm_group", "utm_run_id", "utm_candidate_commit",
                                                       "judged_under", "product_model", "utm_disposition", "owner_decision")}},
    })
count = collections.Counter(c["disposition"] for c in cases)
pcount = collections.Counter(c["parity"]["class"] for c in cases)
by_prio = collections.defaultdict(collections.Counter)
for c in cases:
    by_prio[c["priority"]][c["disposition"]] += 1
out = {"schema_version": 1, "feature": design["feature"],
       "design_sha256": sha(rec / "design.json"),
       "candidate": {"commit": "8c73c8ea80", "corbanu_sha256": "15cb32e9407cc346286d39f24514bb391027db10d2aceb12c1c2798e482c4ae6",
                     "manifest": "candidate/"},
       "dispositions": dict(count), "dispositions_by_priority": {k: dict(v) for k, v in by_prio.items()},
       "parity": dict(pcount), "cases": cases}
(rec / "results.json").write_text(json.dumps(out, indent=1) + "\n")
lab = {"passed": "passed", "failed": "failed", "blocked": "blocked", "accepted_owner_decision": "accepted"}
rows = ["| Case | Pri. | UTM baseline (record, group, candidate, judged under) | UTM | Tart (first attempt) | Parity | Attribution |",
        "| --- | --- | --- | --- | --- | --- | --- |"]
for c in cases:
    u = c["parity"]["utm_baseline"]
    utm = lab[u["utm_disposition"]] + (f" ({u['owner_decision']})" if u["owner_decision"] else "")
    tart = lab[c["disposition"]] + (f" ({c['owner_decision']})" if c["owner_decision"] else "")
    extra = [a["group"] + ": " + a["executor_verdict"] for a in c["attempts"][1:]]
    rows.append(f"| {c['id']} | {c['priority'][0].upper()} | {u['utm_record'].replace('moderate-', '')} {u['utm_group']}, "
                f"`{u['utm_candidate_commit']}`, {u['judged_under']} | {utm} | {tart}" + (f" [{'; '.join(extra)}]" if extra else "")
                + f" | {c['parity']['class']} | {c['parity']['attribution'] or ''} |")
(rec / "parity-table.md").write_text("# Parity table (generated by tools/make_results_par.py)\n\n" + "\n".join(rows) + "\n")
lines = ["# Dispositions (Tart parity run)", "",
         f"Totals: {dict(count)}. By priority: " + "; ".join(f"{k} {dict(v)}" for k, v in sorted(by_prio.items())) + ".", ""]
for c in cases:
    lines.append(f"## {c['id']} ({c['priority']}): {c['disposition']}" + (f" ({c['owner_decision']})" if c['owner_decision'] else ""))
    lines.append("")
    lines.append(c["summary"])
    lines.append("")
    lines.append("Attempts: " + "; ".join(f"{a['group']} ({a['kind']}, executor {a['executor_verdict']}"
                                         + (f", [result]({a['result']['path']})" if a['result'] else "") + ")" for a in c["attempts"]) + ".")
    lines.append(f"Parity: {c['parity']['class']}" + (f", {c['parity']['attribution']}" if c['parity']['attribution'] else "")
                 + (f" ({c['parity']['note']})" if c['parity']['note'] else "") + ".")
    lines.append("")
(rec / "dispositions.md").write_text("\n".join(lines))
print(dict(count), dict(pcount), {k: dict(v) for k, v in by_prio.items()})
