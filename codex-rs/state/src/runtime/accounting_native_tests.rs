fn owner(id: u128) -> ThreadId {
    ThreadId::from_string(&Uuid::from_u128(id).to_string()).unwrap()
}

fn owned(id: u128, time: i64, thread: u128) -> Attempt {
    let mut a = attempt(id, time);
    a.thread_id = owner(thread);
    a
}

// Every column, including future native metadata columns, in one held read snapshot.
async fn whole(conn: &mut SqliteConnection) -> anyhow::Result<Vec<Vec<String>>> {
    let mut result = Vec::new();
    for table in [
        "draft_accounting_attempts",
        "draft_accounting_observations",
        "draft_accounting_price_snapshots",
        "draft_accounting_price_bindings",
        "draft_accounting_estimates",
        "draft_accounting_contributions",
        "draft_accounting_tombstones",
        "draft_accounting_compact_days",
        "draft_accounting_compact_snapshots",
        "draft_accounting_retention_checkpoint",
        "threads",
        "thread_spawn_edges",
        "thread_dynamic_tools",
    ] {
        let columns: Vec<String> =
            sqlx::query_scalar("SELECT name FROM pragma_table_info(?) ORDER BY cid")
                .bind(table)
                .fetch_all(&mut *conn)
                .await?;
        if columns.is_empty() {
            result.push(vec!["<absent>".into()]);
            continue;
        }
        let columns = columns
            .iter()
            .map(|name| format!("\"{name}\""))
            .collect::<Vec<_>>()
            .join(",");
        result.push(
            sqlx::query_scalar(sqlx::AssertSqlSafe(format!(
                "SELECT json_array({columns}) FROM {table} ORDER BY 1"
            )))
            .fetch_all(&mut *conn)
            .await?,
        );
    }
    Ok(result)
}

async fn rows(runtime: &StateRuntime) -> anyhow::Result<Vec<Vec<String>>> {
    let mut tx = runtime.pool.begin().await?;
    let result = whole(&mut tx).await?;
    tx.commit().await?;
    Ok(result)
}

async fn reopen_twice(path: &std::path::Path, expected: &[Vec<String>]) -> anyhow::Result<()> {
    for _ in 0..2 {
        let runtime =
            StateRuntime::init_for_testing(path.to_path_buf(), "synthetic".into()).await?;
        assert_eq!(rows(&runtime).await?, expected);
        runtime.close().await;
        assert!(runtime.pool.is_closed());
    }
    Ok(())
}

async fn seed_native(runtime: &StateRuntime, path: &std::path::Path) -> anyhow::Result<()> {
    for id in [7, 8] {
        runtime
            .upsert_thread(&test_thread_metadata(path, owner(id), path.to_path_buf()))
            .await?;
        sqlx::query("INSERT INTO thread_dynamic_tools (thread_id, position, name, description, input_schema) VALUES (?, 0, 'fixture', 'synthetic', '{}')")
            .bind(owner(id).to_string()).execute(runtime.pool.as_ref()).await?;
    }
    runtime
        .upsert_thread_spawn_edge(
            owner(/*id*/ 7),
            owner(/*id*/ 8),
            crate::DirectionalThreadSpawnEdgeStatus::Closed,
        )
        .await?;
    Ok(())
}

async fn seed(runtime: &StateRuntime, path: &std::path::Path) -> anyhow::Result<()> {
    seed_native(runtime, path).await?;
    let store = install(runtime).await?;
    for a in [
        attempt(/*id*/ 1, /*dispatch*/ 0),
        attempt(/*id*/ 2, DETAIL_MS - 1),
        owned(/*id*/ 3, DETAIL_MS - 1, /*thread*/ 8),
    ] {
        save(&store, &a, &[snapshot()]).await?;
    }
    store.maintain_retention(DETAIL_MS - 1).await
}

// Explicit case expectations; only untouched rows are copied, never generated by C2.
fn deleted(baseline: &[Vec<String>], ids: &[u128], time: i64) -> anyhow::Result<Vec<Vec<String>>> {
    let all = ids.contains(&8);
    let removed = if all { vec![1, 2, 3] } else { vec![1, 2] };
    let mut tombstones = vec![(1, REPLAY_MS), (2, DETAIL_MS - 1 + REPLAY_MS)];
    if all {
        tombstones.push((3, DETAIL_MS - 1 + REPLAY_MS));
    }
    let mut result = retained_rows(
        baseline,
        &removed,
        &[],
        &tombstones,
        if all { &[] } else { &[1000] },
        time,
    )?;
    for index in [10, 12] {
        result[index].retain(|row| {
            let row: serde_json::Value = serde_json::from_str(row).unwrap();
            !ids.iter().any(|id| row[0] == owner(*id).to_string())
        });
    }
    result[11].clear();
    Ok(result)
}

